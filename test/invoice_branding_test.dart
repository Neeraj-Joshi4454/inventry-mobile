Map<String, dynamic> _invoiceJson({required String partyKey}) => {
  'business': {
    'name': 'Joshi Building Materials',
    'address': {'line1': '12 Market Road', 'city': 'Pune', 'state': 'Maharashtra', 'pincode': '411001'},
    'phone': '9876543210',
    'email': 'billing@joshi.test',
    'gstin': '27ABCDE1234F1Z5',
    'invoiceFooterNote': 'Thank you!',
  },
  partyKey: {'name': 'Ravi'},
  'invoiceNumber': 'INV-0001',
  'invoiceDate': '2026-10-11T00:00:00.000Z',
  'taxType': 'CGST_SGST',
  'items': [
    {
      'productName': 'Cement',
      'hsnCode': '2523',
      'quantity': 10,
      'unitSymbol': 'bag',
      'rate': 400,
      'discount': 0,
      'taxableValue': 4000,
      'taxRate': 28,
      'cgst': 560,
      'sgst': 560,
      'igst': 0,
      'lineTotal': 5120,
    },
  ],
  'subTotal': 4000,
  'discountAmount': 0,
  'taxableAmount': 4000,
  'cgstAmount': 560,
  'sgstAmount': 560,
  'igstAmount': 0,
  'totalTax': 1120,
  'grandTotal': 5120,
};

void main() {
  final logo = File('assets/brand/logo_mark.png').readAsBytesSync();

  test('sale invoice carries business phone, email and full address', () {
    final invoice = SaleInvoice.fromJson(_invoiceJson(partyKey: 'customer'));
    expect(invoice.business.contactLine, 'Ph: 9876543210  ·  billing@joshi.test');
    expect(invoice.business.addressLine, '12 Market Road, Pune, Maharashtra, 411001');
  });

  test('every invoice carries the Stock Yard attribution with the year', () {
    expect(
      Brand.invoiceAttribution(2026),
      'This invoice is electronically generated by the Stock Yard app. © 2026 Stock Yard. All rights reserved.',
    );
    expect(Brand.invoiceAttribution(), contains('© ${DateTime.now().year} Stock Yard'));
  });

  test('contact line is omitted when no phone or email is set', () {
    expect(const InvoiceParty(name: 'X').contactLine, isNull);
  });

  test('sale and purchase PDFs build with and without a logo', () async {
    final sale = SaleInvoice.fromJson(_invoiceJson(partyKey: 'customer'));
    final purchase = PurchaseInvoice.fromJson(_invoiceJson(partyKey: 'supplier'));

    for (final bytes in [logo, null]) {
      final saleDoc = await buildInvoicePdf(sale, logo: bytes);
      final purchaseDoc = await buildPurchaseInvoicePdf(purchase, logo: bytes);
      expect(await saleDoc.save(), isNotEmpty);
      expect(await purchaseDoc.save(), isNotEmpty);
    }
  });
}
